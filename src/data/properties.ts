const used: Partial<Record<Property["category"], number>> = {};

export const properties: Property[] = rawProperties.map((p) => {
  // A listing-specific `photo` wins and doesn't use up a slot in the category rotation.
  if (p.photo) return { ...p, image: p.photo };
  const index = used[p.category] ?? 0;
  used[p.category] = index + 1;
  const gallery = categoryGallery[p.category];
  return { ...p, image: gallery[index % gallery.length] };
});

export function getPropertyById(id: string) {
  return properties.find((p) => p.id === id);
}
